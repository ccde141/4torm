import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { ConvectionParticipantDisplay } from './participant-display.js';
import { createSession, loadSession, saveSession } from '../infrastructure/session-store.js';
import { convectionDisplayMessages, editConvectionDisplay } from '../application/display-history.js';
import { convectionContext } from './compaction-context.js';

test('stopping after a committed boundary preserves both segments and informs the model of unfinished execution facts', async t => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'convection-partial-display-'));
  t.after(() => fs.rm(directory, { recursive: true, force: true }));
  const session = await createSession(directory, { chairAgentId: 'chair', participantAgentIds: ['member'] });
  session.publicMessages = [{ speaker: '人类', content: '真实要求', timestamp: 1 }];
  const display = new ConvectionParticipantDisplay({ id: 'member', name: '成员' }, 'same-run');
  display.receive({ type: 'token', label: '成员', chunk: '压缩前正文' });
  display.receive({ type: 'reasoning', label: '成员', chunk: '原始思考' });
  display.receive({ type: 'tool-call', label: '成员', tool: 'read', args: { path: 'evidence' } });
  display.receive({ type: 'tool-result', label: '成员', tool: 'read', result: '原始证据' });
  const compaction = { id: 'compact-one', summary: '交接背景' };
  session.publicExecutionDraft = display.snapshot(compaction);
  await saveSession(directory, session);
  assert.equal((await loadSession(directory, session.id))?.publicExecutionDraft?.compactions?.[0].toolOffset, 1);
  display.compactions.push(display.boundary(compaction));
  display.receive({ type: 'token', label: '成员', chunk: '压缩后正文' });
  await display.preserve(directory, session, undefined, true);
  const restored = (await loadSession(directory, session.id))!;
  const partial = convectionDisplayMessages(restored).at(-1)!;
  assert.equal(partial.content, '压缩前正文压缩后正文');
  assert.equal(partial.reasoning, '原始思考');
  assert.equal(partial.toolCalls?.[0].result, '原始证据');
  assert.equal(partial.compactions?.length, 1);
  assert.equal(partial.execution?.status, 'stopped');
  assert.equal(partial.runId, 'same-run');
  assert.equal(restored.publicMessages.length, 2);
  assert.equal(restored.publicExecutionDraft, undefined);
  const modelContext = convectionContext(restored.publicMessages);
  assert.match(modelContext.at(-1)!.content, /执行未完成：已停止/);
  assert.match(modelContext.at(-1)!.content, /原始证据/);
  assert.doesNotMatch(modelContext.at(-1)!.content, /原始思考/);
  assert.equal(modelContext.at(-1)!.origin, 'framework');
  editConvectionDisplay(restored, 0, '修订真实要求');
  assert.equal(restored.publicMessages[0].content, '修订真实要求');
});
